"""contracts.py
Shared data contracts between Person A (Agent Brain) and Person B (Data & Delivery).
Defined in Phase 0. Do not modify without mutual agreement.
"""

from dataclasses import dataclass, field, asdict
from typing import Any, Dict, List, Optional, Tuple


@dataclass
class PlanQuery:
    """A single planned SQL query within a Plan."""
    query_id: str                          # e.g., "Q1", "Q2"
    sql: str                               # The SQL statement
    purpose: str                           # Short explanation of what this query measures

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "PlanQuery":
        return cls(
            query_id=data.get("query_id", ""),
            sql=data.get("sql", ""),
            purpose=data.get("purpose", "")
        )


@dataclass
class Plan:
    """The structured execution plan generated by planner.py."""
    metric: str                            # e.g., "revenue", "units_sold", "order_count"
    time_window: str                       # e.g., "last_complete_month", "1997-Q1"
    comparison_period: Optional[str] = None # e.g., "previous_month", "previous_year"
    filters: Dict[str, Any] = field(default_factory=dict) # e.g., {"region": "South"}
    drill_down_dimensions: List[str] = field(default_factory=list) # e.g., ["region", "product", "time"]
    query_list: List[PlanQuery] = field(default_factory=list)
    needs_clarification: bool = False
    clarification_message: Optional[str] = None
    is_refusal: bool = False
    refusal_reason: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "Plan":
        queries = [
            PlanQuery.from_dict(q) if isinstance(q, dict) else q
            for q in data.get("query_list", [])
        ]
        return cls(
            metric=data.get("metric", ""),
            time_window=data.get("time_window", ""),
            comparison_period=data.get("comparison_period"),
            filters=data.get("filters", {}),
            drill_down_dimensions=data.get("drill_down_dimensions", []),
            query_list=queries,
            needs_clarification=data.get("needs_clarification", False),
            clarification_message=data.get("clarification_message"),
            is_refusal=data.get("is_refusal", False),
            refusal_reason=data.get("refusal_reason")
        )


@dataclass
class QueryResult:
    """The result of executing a query, returned by executor.py."""
    query_id: str                          # Matches PlanQuery.query_id (e.g. "Q1")
    sql: str                               # The executed SQL
    columns: List[str] = field(default_factory=list) # Column names
    rows: List[Tuple[Any, ...]] = field(default_factory=list) # Raw data rows
    row_count: int = 0                     # Number of rows returned
    error: Optional[str] = None            # Execution error message if failed

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "QueryResult":
        rows = [tuple(r) if isinstance(r, list) else r for r in data.get("rows", [])]
        return cls(
            query_id=data.get("query_id", ""),
            sql=data.get("sql", ""),
            columns=data.get("columns", []),
            rows=rows,
            row_count=data.get("row_count", 0),
            error=data.get("error")
        )


@dataclass
class ValidationResult:
    """Sanity check outcome for an executed query, returned by validator.py."""
    status: str                            # "pass", "fail", or "suspicious"
    reason: Optional[str] = None           # Details if fail or suspicious
    check_name: str = ""                   # Name of check (e.g., "reconciliation", "execution")

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "ValidationResult":
        return cls(
            status=data.get("status", "pass"),
            reason=data.get("reason"),
            check_name=data.get("check_name", "")
        )


@dataclass
class Finding:
    """A verified analytical finding holding a statement linked to a query ID."""
    statement: str                         # e.g., "South region revenue fell 18%"
    value: Optional[float] = None          # Numeric value
    formatted_value: Optional[str] = None  # e.g., "$12,450.00" or "-18.2%"
    query_id: str = ""                     # e.g., "Q1" - required for traceability
    dimension: Optional[str] = None        # e.g., "region", "product", "time"
    metadata: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class AgentResponse:
    """The complete response assembled at the end of the agent loop."""
    question: str
    status: str                            # "success", "needs_clarification", "refused", "error"
    headline: str = ""
    assumptions: List[str] = field(default_factory=list)
    plan: Optional[Plan] = None
    findings: List[Finding] = field(default_factory=list)
    query_results: Dict[str, QueryResult] = field(default_factory=dict)
    validation_results: Dict[str, List[ValidationResult]] = field(default_factory=dict)
    trace: List[Dict[str, Any]] = field(default_factory=list)
    error_message: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)
