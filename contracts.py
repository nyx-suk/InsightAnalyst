"""contracts.py
Shared data contracts between Person A (Agent Brain) and Person B (Data & Delivery).
Defined in Phase 0. Do not modify without mutual agreement.
"""

from dataclasses import dataclass, field, asdict
from typing import Any, Dict, List, Optional, Tuple


@dataclass
class PlanQuery:
    """A single planned SQL query within a Plan."""
    query_id: str                          # e.g., "Q1", "Q2"
    sql: str                               # The SQL statement
    purpose: str                           # Short explanation of what this query measures

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "PlanQuery":
        return cls(
            query_id=data.get("query_id", ""),
            sql=data.get("sql", ""),
            purpose=data.get("purpose", "")
        )


@dataclass
class Plan:
    """The structured execution plan generated by planner.py."""
    metric: str                            # e.g., "revenue", "units_sold", "order_count"
    time_window: str                       # e.g., "last_complete_month", "1997-Q1"
    comparison_period: Optional[str] = None # e.g., "previous_month", "previous_year"
    filters: Dict[str, Any] = field(default_factory=dict) # e.g., {"region": "South"}
    drill_down_dimensions: List[str] = field(default_factory=list) # e.g., ["region", "product", "time"]
    query_list: List[PlanQuery] = field(default_factory=list)
    assumptions: List[str] = field(default_factory=list)
    question: str = ""
    needs_clarification: bool = False
    clarification_message: Optional[str] = None
    is_refusal: bool = False
    refusal_reason: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "Plan":
        raw_queries = data.get("queries") if "queries" in data else data.get("query_list", [])
        queries = [
            PlanQuery.from_dict(q) if isinstance(q, dict) else q
            for q in raw_queries
        ]
        time_win = data.get("time_window", "")
        if isinstance(time_win, dict):
            time_win = time_win.get("value") or time_win.get("type", "")
        comp_win = data.get("comparison_window") if "comparison_window" in data else data.get("comparison_period")
        if isinstance(comp_win, dict):
            comp_win = comp_win.get("value") or comp_win.get("type", "")

        return cls(
            metric=data.get("metric", ""),
            time_window=str(time_win),
            comparison_period=str(comp_win) if comp_win is not None else None,
            filters=data.get("filters", {}),
            drill_down_dimensions=data.get("drill_down_dimensions", []),
            query_list=queries,
            assumptions=data.get("assumptions", []),
            question=data.get("question", ""),
            needs_clarification=data.get("needs_clarification", bool(data.get("clarification_question"))),
            clarification_message=data.get("clarification_question") or data.get("clarification_message"),
            is_refusal=data.get("refused", data.get("is_refusal", False)),
            refusal_reason=data.get("refusal_reason")
        )


@dataclass
class QueryResult:
    """The result of executing a query, returned by executor.py."""
    query_id: str                          # Matches PlanQuery.query_id (e.g. "Q1")
    sql: str                               # The executed SQL
    columns: List[str] = field(default_factory=list) # Column names
    rows: List[Tuple[Any, ...]] = field(default_factory=list) # Raw data rows
    row_count: int = 0                     # Number of rows returned
    error: Optional[str] = None            # Execution error message if failed

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "QueryResult":
        rows = [tuple(r) if isinstance(r, list) else r for r in data.get("rows", [])]
        return cls(
            query_id=data.get("query_id", ""),
            sql=data.get("sql", ""),
            columns=data.get("columns", []),
            rows=rows,
            row_count=data.get("row_count", 0),
            error=data.get("error")
        )


@dataclass
class ValidationResult:
    """Sanity check outcome for an executed query, returned by validator.py."""
    status: str                            # "pass", "fail", or "suspicious"
    reason: Optional[str] = None           # Details if fail or suspicious
    check_name: str = ""                   # Name of check (e.g., "reconciliation", "execution")

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "ValidationResult":
        return cls(
            status=data.get("status", "pass"),
            reason=data.get("reason"),
            check_name=data.get("check_name", "")
        )


@dataclass
class Finding:
    """
    A verified analytical finding holding a template, values, and query ID.
    Key rule: Numbers appear only in values and are filled into template by code.
    The LLM never types a number directly in findings.
    """
    id: str = ""                           # e.g., "F1", "headline"
    kind: str = "headline"                 # 'headline' | 'driver' | 'trend'
    template: str = ""                     # e.g., "South revenue fell {pct_change} [{query_id}]"
    values: Dict[str, Any] = field(default_factory=dict) # placeholder name -> number/str
    query_id: str = ""                     # e.g., "Q1" - required for traceability

    # Backward compatibility fields for earlier phases and integration tests
    statement: str = ""
    value: Optional[float] = None
    formatted_value: Optional[str] = None
    dimension: Optional[str] = None
    metadata: Dict[str, Any] = field(default_factory=dict)

    def render(self) -> str:
        """Fill placeholder values and query_id into template safely."""
        tmpl = self.template or self.statement
        if not tmpl:
            return ""
        kwargs = dict(self.values)
        if "query_id" not in kwargs and self.query_id:
            kwargs["query_id"] = self.query_id
        try:
            return tmpl.format(**kwargs)
        except Exception:
            out = tmpl
            for k, v in kwargs.items():
                out = out.replace(f"{{{k}}}", str(v))
            return out

    def __post_init__(self):
        if not self.statement and self.template:
            self.statement = self.render()
        elif not self.template and self.statement:
            self.template = self.statement

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "Finding":
        return cls(
            id=data.get("id", ""),
            kind=data.get("kind", "headline"),
            template=data.get("template", data.get("statement", "")),
            values=data.get("values", {}),
            query_id=data.get("query_id", ""),
            statement=data.get("statement", ""),
            value=data.get("value"),
            formatted_value=data.get("formatted_value"),
            dimension=data.get("dimension"),
            metadata=data.get("metadata", {})
        )


@dataclass
class TraceEvent:
    """
    A structured event emitted during agent loop execution.
    events: 'plan' | 'query' | 'check' | 'retry' | 'drilldown' | 'done' | 'error'
    """
    step: int
    event: str                             # 'plan' | 'query' | 'check' | 'retry' | 'drilldown' | 'done' | 'error'
    message: str
    query_id: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "TraceEvent":
        return cls(
            step=data.get("step", 0),
            event=data.get("event", ""),
            message=data.get("message", ""),
            query_id=data.get("query_id")
        )


@dataclass
class AgentRun:
    """
    The complete record of an agent run over a user question.
    status: 'complete' | 'partial' | 'failed' | 'clarify' | 'refused'
    """
    question: str
    plan: Optional[Plan] = None
    queries: List[QueryResult] = field(default_factory=list)
    validations: List[ValidationResult] = field(default_factory=list)
    findings: List[Finding] = field(default_factory=list)
    trace: List[TraceEvent] = field(default_factory=list)
    assumptions: List[str] = field(default_factory=list)
    status: str = "complete"               # 'complete' | 'partial' | 'failed' | 'clarify' | 'refused'
    error: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "AgentRun":
        raw_plan = data.get("plan")
        plan = None
        if isinstance(raw_plan, dict):
            plan = Plan.from_dict(raw_plan)
        elif isinstance(raw_plan, Plan):
            plan = raw_plan

        queries = [
            QueryResult.from_dict(q) if isinstance(q, dict) else q
            for q in data.get("queries", [])
        ]
        validations = [
            ValidationResult.from_dict(v) if isinstance(v, dict) else v
            for v in data.get("validations", [])
        ]
        findings = [
            Finding.from_dict(f) if isinstance(f, dict) else f
            for f in data.get("findings", [])
        ]
        trace = [
            TraceEvent.from_dict(t) if isinstance(t, dict) else t
            for t in data.get("trace", [])
        ]

        return cls(
            question=data.get("question", ""),
            plan=plan,
            queries=queries,
            validations=validations,
            findings=findings,
            trace=trace,
            assumptions=data.get("assumptions", []),
            status=data.get("status", "complete"),
            error=data.get("error")
        )


@dataclass
class AgentResponse:
    """The complete response assembled at the end of the agent loop (backward compatibility)."""
    question: str
    status: str                            # "success", "needs_clarification", "refused", "error"
    headline: str = ""
    assumptions: List[str] = field(default_factory=list)
    plan: Optional[Plan] = None
    findings: List[Finding] = field(default_factory=list)
    query_results: Dict[str, QueryResult] = field(default_factory=dict)
    validation_results: Dict[str, List[ValidationResult]] = field(default_factory=dict)
    trace: List[Dict[str, Any]] = field(default_factory=list)
    error_message: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)
