
"""
executor.py

Person B: Safe, read-only SQL executor for InsightAnalyst.

Interface expected by Person A:
    execute_query(query_id, sql) -> QueryResult
"""

import sqlite3
from pathlib import Path

from contracts import QueryResult


# Locate the project root and database automatically.
PROJECT_ROOT = Path(__file__).resolve().parent
DB_PATH = PROJECT_ROOT / "data" / "northwind.db"


# Only these SQLite operations are allowed.
# All other database operations are denied.
ALLOWED_ACTIONS = {
    sqlite3.SQLITE_SELECT,
    sqlite3.SQLITE_READ,
    sqlite3.SQLITE_FUNCTION,
}

# Recursive CTE support, if available in this Python version.
if hasattr(sqlite3, "SQLITE_RECURSIVE"):
    ALLOWED_ACTIONS.add(sqlite3.SQLITE_RECURSIVE)


def read_only_authorizer(action, arg1, arg2, database, trigger):
    """
    SQLite calls this function before performing database operations.

    Allow reading and SELECT operations.
    Deny database modifications and other operations.
    """

    if action in ALLOWED_ACTIONS:
        return sqlite3.SQLITE_OK

    return sqlite3.SQLITE_DENY


def execute_query(query_id: str, sql: str) -> QueryResult:
    """
    Execute one read-only SQL query and return a QueryResult.

    Args:
        query_id: Query identifier such as Q1.
        sql: SQL statement generated by Person A.

    Returns:
        QueryResult containing columns, rows, row_count or error.
    """

    if not isinstance(sql, str) or not sql.strip():
        return QueryResult(
            query_id=query_id,
            sql=sql if isinstance(sql, str) else "",
            error="INVALID_QUERY: SQL query cannot be empty."
        )

    if not DB_PATH.exists():
        return QueryResult(
            query_id=query_id,
            sql=sql,
            error=f"DATABASE_NOT_FOUND: {DB_PATH}"
        )

    connection = None

    try:
        # mode=ro opens SQLite in read-only mode.
        database_uri = DB_PATH.as_uri() + "?mode=ro"

        connection = sqlite3.connect(
            database_uri,
            uri=True,
            timeout=10
        )

        # Add a second layer of protection.
        connection.execute("PRAGMA query_only = ON")

        # SQLite itself decides which operations are permitted.
        connection.set_authorizer(read_only_authorizer)

        cursor = connection.cursor()

        # execute() accepts one SQL statement.
        # Multiple statements are rejected by sqlite3.
        cursor.execute(sql)

        rows = cursor.fetchall()

        columns = (
            [description[0] for description in cursor.description]
            if cursor.description
            else []
        )

        return QueryResult(
            query_id=query_id,
            sql=sql,
            columns=columns,
            rows=rows,
            row_count=len(rows),
            error=None
        )

    except sqlite3.Error as error:
        return QueryResult(
            query_id=query_id,
            sql=sql,
            error=f"SQL_EXECUTION_ERROR: {error}"
        )

    except Exception as error:
        return QueryResult(
            query_id=query_id,
            sql=sql,
            error=f"EXECUTOR_ERROR: {error}"
        )

    finally:
        if connection is not None:
            connection.close()


# Convenient alias for integration with Person A's agent loop.
executor_fn = execute_query
